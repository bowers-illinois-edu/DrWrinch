#' DrWrinch: Fully Specified Bayes Factors for Process Tracing
#'
#' Computes Bayes factors for a working theory \eqn{H_1} against a single
#' rival \eqn{H_R} under two generative models: a binomial model for
#' open-ended evidence and a hypergeometric urn model for bounded
#' archives. Both constructions tilt in favor of the rival, so the
#' reported Bayes factor is a lower bound on the evidence for the
#' working theory. Sensitivity functions show how the Bayes factor moves
#' under departures from the baseline assumptions.
#'
#' The package is named after Dorothy Maud Wrinch (1894--1976), whose
#' joint papers with Harold Jeffreys (1919, 1921, 1923) developed the
#' framework that became Jeffreys's theory of Bayes factors. See
#' <https://en.wikipedia.org/wiki/Dorothy_Maud_Wrinch>.
#'
